export function localizeValidationMessage(message: string): string {
  if (!message) return message;

  const key = message.startsWith('validation.')
    ? message
    : LEGACY_ENGLISH_MESSAGES[message];

  if (key) {
    const translated = t(key);
    return translated !== key ? translated : message;
  }

  return message;
}
