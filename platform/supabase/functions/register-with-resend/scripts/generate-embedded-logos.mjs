import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const assetsDir = path.join(__dirname, '../assets');
const functionsDir = path.resolve(__dirname, '../..');

// Email-only copies with transparent background; the app icons must stay opaque.
const restaurantLogo = fs.readFileSync(path.join(assetsDir, 'logo-restaurant-email.png'));
const clientLogo = fs.readFileSync(path.join(assetsDir, 'logo-client-email.png'));

const toDataUri = (bytes) => `data:image/png;base64,${bytes.toString('base64')}`;

const registerOut = `export const RESTAURANT_EMBEDDED_LOGO_DATA_URI = "${toDataUri(restaurantLogo)}";

export const CLIENT_EMBEDDED_LOGO_DATA_URI = "${toDataUri(clientLogo)}";

/** @deprecated use RESTAURANT_EMBEDDED_LOGO_DATA_URI */
export const EMBEDDED_LOGO_DATA_URI = RESTAURANT_EMBEDDED_LOGO_DATA_URI;
`;

const demoOut = `// NOOWE logo (base64 PNG) — generated by register-with-resend/scripts/generate-embedded-logos.mjs
// Kept local so the Supabase deploy bundles it with this function.
export const NOOWE_EMBEDDED_LOGO_DATA_URI = "${toDataUri(clientLogo)}";
`;

const registerTarget = path.join(__dirname, '../embedded-logos.ts');
const demoTarget = path.join(functionsDir, 'send-demo-code/embedded-logo.ts');
fs.writeFileSync(registerTarget, registerOut);
fs.writeFileSync(demoTarget, demoOut);
console.log(`Wrote ${registerTarget} (restaurant ${restaurantLogo.length} B, client ${clientLogo.length} B)`);
console.log(`Wrote ${demoTarget} (client ${clientLogo.length} B)`);
